import React, { useState, useEffect } from 'react';
import { Search, FileText, Download, ExternalLink, CheckCircle2, ChevronRight, AlertCircle, Database } from 'lucide-react';
import { cn } from '../lib/utils';
import { motion, AnimatePresence } from 'motion/react';
import { searchOssNotes } from '../services/geminiService';
import { logTelemetry } from '../services/telemetryService';

interface OssNote {
  id: string;
  title: string;
  component: string;
  releasedOn: string;
  status: string;
  priority: string;
  category: string;
  shortText: string;
}

// Mock OSS Notes Data as fallback/initial
const INITIAL_NOTES: OssNote[] = [
  {
    id: "3389145",
    title: "EWM: Performance Issue during wave release with high volume data",
    component: "SCM-EWM-WAV",
    releasedOn: "12.02.2024",
    status: "Released",
    priority: "High",
    category: "Program Error",
    shortText: "During the wave release process with a very large number of warehouse requests, the system may experience significant performance degradation or time-out dumps."
  },
  {
    id: "3298112",
    title: "RF Framework: Screen layout issues on latest Zebra scanners",
    component: "SCM-EWM-RF",
    releasedOn: "05.11.2023",
    status: "Released",
    priority: "Medium",
    category: "Program Error",
    shortText: "When rendering standard RF screens on newer generation Zebra devices, certain UI elements may overlap or become unclickable due to rendering engine updates."
  },
  {
    id: "3410291",
    title: "Advanced Shipping & Receiving: Inconsistencies during TM-EWM integration",
    component: "SCM-EWM-SR",
    releasedOn: "28.03.2024",
    status: "Released",
    priority: "Very High",
    category: "Program Error",
    shortText: "In ASR scenarios involving cross-delivery handling units, updates from Transportation Management (TM) may not reflect accurately in EWM stock structures."
  }
];

export function OssNotesView() {
  const [searchQuery, setSearchQuery] = useState('');
  const [activeSearchQuery, setActiveSearchQuery] = useState('');
  const [selectedNote, setSelectedNote] = useState<string | null>(null);
  const [isSearching, setIsSearching] = useState(false);
  const [downloadedNotes, setDownloadedNotes] = useState<Set<string>>(new Set());
  const [notes, setNotes] = useState<OssNote[]>(INITIAL_NOTES);
  const [error, setError] = useState<string | null>(null);

  const handleSearch = async (e: React.FormEvent) => {
    e.preventDefault();
    if (isSearching || !searchQuery.trim()) return;
    setIsSearching(true);
    setError(null);
    const startTime = Date.now();
    let results: any = null;
    let isSuccess: 'SUCCESS' | 'FAILURE' = 'SUCCESS';
    try {
      results = await searchOssNotes(searchQuery);
      setNotes(results);
      setActiveSearchQuery(searchQuery);
    } catch (err: any) {
      isSuccess = 'FAILURE';
      setError(err.message || "Failed to retrieve notes");
    } finally {
      setIsSearching(false);
      const endTime = Date.now();
      const latency = endTime - startTime;
      logTelemetry(
        'OSS Note Search',
        searchQuery.length,
        results ? JSON.stringify(results).length : 0,
        latency,
        isSuccess
      ).catch(e => console.error("Telemetry failed: ", e));
    }
  };

  const handleDownload = (id: string, e: React.MouseEvent) => {
    e.stopPropagation();
    
    // Find the note
    const note = notes.find(n => n.id === id);
    if (note) {
      const content = `SAP Note: ${note.id}
Title: ${note.title}
Component: ${note.component}
Priority: ${note.priority}
Released On: ${note.releasedOn}
Status: ${note.status}
Category: ${note.category}

Symptom / Reason:
${note.shortText}

Source: https://me.sap.com/notes/${note.id}
Generated by Applet.`;

      const blob = new Blob([content], { type: 'text/plain' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `SAP_Note_${note.id}.txt`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }
    
    setDownloadedNotes(prev => {
      const newSet = new Set(prev);
      newSet.add(id);
      return newSet;
    });
  };

  const displayNotes = notes;

  return (
    <div className="flex-1 flex flex-col relative w-full h-full overflow-hidden bg-[#02040a]">
      {/* Background elements */}
      <div className="absolute inset-0 z-0 bg-[url('https://transparenttextures.com/patterns/cubes.png')] opacity-[0.02] mix-blend-overlay"></div>
      
      {/* Header */}
      <header className="min-h-[4rem] px-4 md:px-8 py-6 border-b border-white/5 relative z-10 bg-[#02040a]/80 backdrop-blur-xl shrink-0 flex flex-col md:flex-row items-start md:items-center justify-between gap-4">
        <div className="flex flex-col">
          <div className="flex items-center gap-3">
            <div className="w-1.5 h-6 bg-amber-500 rounded-sm shadow-[0_0_10px_rgba(245,158,11,0.5)] shrink-0"></div>
            <h1 className="text-lg md:text-xl font-display font-semibold tracking-wider text-slate-100 flex items-center gap-3 uppercase">
              <Database className="text-amber-400 shrink-0" size={24} />
              <span className="truncate">SAP OSS NOTES REPOSITORY</span>
            </h1>
          </div>
          <p className="text-[10px] md:text-xs font-mono text-slate-500 tracking-widest uppercase mt-2 ml-4">
            Direct integration with SAP Support Portal
          </p>
        </div>
      </header>

      {/* Content */}
      <div className="flex-1 overflow-y-auto p-4 md:p-8 z-10 scrollbar-thin scrollbar-thumb-white/10 scrollbar-track-transparent">
        <div className="w-full max-w-5xl mx-auto space-y-6">
          
          <form onSubmit={handleSearch} className="relative group">
            <div className="absolute inset-y-0 left-0 pl-4 flex items-center pointer-events-none">
              <Search className="h-5 w-5 text-slate-500 group-focus-within:text-amber-400 transition-colors" />
            </div>
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search by Note Number, Component, or Keyword (e.g., 'EWM Performance')"
              className="w-full pl-12 pr-4 py-4 bg-[#0f172a]/40 border border-white/10 rounded-xl text-slate-200 font-mono text-sm focus:outline-none focus:border-amber-500/50 focus:bg-[#0f172a]/60 shadow-[inset_0_0_20px_rgba(0,0,0,0.2)] transition-all placeholder-slate-500"
            />
            <button 
              type="submit"
              disabled={isSearching}
              className="absolute right-4 top-1/2 -translate-y-1/2 px-4 py-1.5 bg-amber-500/20 text-amber-200 font-mono text-xs tracking-widest rounded border border-amber-500/40 hover:bg-amber-500/30 transition-all font-bold uppercase disabled:opacity-50 flex items-center gap-2"
            >
              {isSearching ? (
                <>
                  <Database size={12} className="animate-spin-slow" />
                  Searching
                </>
              ) : (
                'Search'
              )}
            </button>
          </form>

          <div className="space-y-4">
            {error && (
              <div className="p-4 mb-4 bg-rose-500/10 border border-rose-500/30 text-rose-400 rounded-xl font-mono text-sm">
                <AlertCircle className="inline mr-2" size={16} />
                {error}
              </div>
            )}
            {isSearching ? (
              <div className="flex justify-center p-12">
                <div className="flex items-center gap-3 text-amber-400 font-mono tracking-widest text-sm animate-pulse">
                  <Database size={16} className="animate-spin-slow" />
                  QUERYING SAP SUPPORT BACKBONE...
                </div>
              </div>
            ) : displayNotes.length > 0 ? (
              <div className="grid grid-cols-1 gap-4">
                {displayNotes.map((note) => (
                  <motion.div
                    initial={{ opacity: 0, y: 10 }}
                    animate={{ opacity: 1, y: 0 }}
                    key={note.id}
                    onClick={() => setSelectedNote(selectedNote === note.id ? null : note.id)}
                    className={cn(
                      "bg-[#0f172a]/40 border rounded-xl overflow-hidden cursor-pointer transition-all duration-300",
                      selectedNote === note.id 
                        ? "border-amber-500/50 shadow-[0_0_20px_rgba(245,158,11,0.1)]" 
                        : "border-white/5 hover:border-white/20 hover:bg-[#0f172a]/60"
                    )}
                  >
                    <div className="p-4 md:p-5 flex flex-col md:flex-row gap-4 items-start md:items-center justify-between">
                      <div className="flex items-start gap-4 flex-1">
                        <div className={cn(
                          "w-10 h-10 rounded-lg flex items-center justify-center shrink-0 border",
                          note.priority === 'Very High' ? "bg-rose-500/10 border-rose-500/30 text-rose-400" :
                          note.priority === 'High' ? "bg-amber-500/10 border-amber-500/30 text-amber-400" :
                          note.category === 'FAQ' ? "bg-cyan-500/10 border-cyan-500/30 text-cyan-400" :
                          "bg-slate-500/10 border-slate-500/30 text-slate-400"
                        )}>
                          <FileText size={20} />
                        </div>
                        <div>
                          <div className="flex items-center gap-3 mb-1 flex-wrap">
                            <span className="font-mono text-amber-400 font-bold">{note.id}</span>
                            <span className="text-xs font-mono px-2 py-0.5 rounded border border-white/10 bg-white/5 text-slate-300">{note.component}</span>
                            {note.priority === 'Very High' && (
                              <span className="text-[10px] font-mono px-1.5 py-0.5 rounded bg-rose-500/20 text-rose-300 border border-rose-500/30">HOT NEWS</span>
                            )}
                          </div>
                          <h3 className="text-sm font-semibold text-slate-200">{note.title}</h3>
                        </div>
                      </div>
                      
                      <div className="flex items-center gap-4 w-full md:w-auto">
                        <div className="flex flex-col items-start md:items-end flex-1 md:flex-none mr-2">
                          <span className="text-[10px] font-mono text-slate-500 tracking-wider">RELEASED</span>
                          <span className="text-xs font-mono text-slate-300">{note.releasedOn}</span>
                        </div>
                        
                        {downloadedNotes.has(note.id) ? (
                          <div className="flex items-center gap-1.5 px-3 py-1.5 bg-emerald-500/10 border border-emerald-500/30 text-emerald-400 rounded-md text-[10px] font-mono tracking-widest shrink-0">
                            <CheckCircle2 size={14} />
                            DOWNLOADED
                          </div>
                        ) : (
                          <button 
                            onClick={(e) => handleDownload(note.id, e)}
                            className="flex items-center gap-1.5 px-3 py-1.5 bg-white/5 hover:bg-amber-500/20 border border-white/10 hover:border-amber-500/50 text-slate-300 hover:text-amber-300 rounded-md text-[10px] font-mono tracking-widest shrink-0 transition-all font-bold"
                          >
                            <Download size={14} />
                            DOWNLOAD
                          </button>
                        )}
                        <a 
                          href={`https://me.sap.com/notes/${note.id}`}
                          target="_blank"
                          rel="noopener noreferrer"
                          onClick={(e) => e.stopPropagation()}
                          className="flex items-center gap-1.5 px-3 py-1.5 bg-cyan-500/10 hover:bg-cyan-500/20 border border-cyan-500/30 hover:border-cyan-500/50 text-cyan-400 hover:text-cyan-300 rounded-md text-[10px] font-mono tracking-widest shrink-0 transition-all font-bold shadow-[0_0_10px_rgba(6,182,212,0.15)]"
                          title="Open in SAP For Me"
                        >
                          <ExternalLink size={14} />
                          SAP FOR ME
                        </a>
                        <ChevronRight size={20} className={cn("text-slate-500 transition-transform", selectedNote === note.id && "rotate-90")} />
                      </div>
                    </div>

                    <AnimatePresence>
                      {selectedNote === note.id && (
                        <motion.div
                          initial={{ height: 0, opacity: 0 }}
                          animate={{ height: 'auto', opacity: 1 }}
                          exit={{ height: 0, opacity: 0 }}
                          className="border-t border-white/5 overflow-hidden"
                        >
                          <div className="p-4 md:p-6 bg-[#0a0f1c]">
                            <div className="flex items-center gap-2 text-xs font-mono text-slate-400 mb-3 uppercase tracking-widest">
                              <AlertCircle size={14} />
                              Symptom / Reason
                            </div>
                            <p className="text-sm text-slate-300 leading-relaxed mb-6 font-mono">
                              {note.shortText}
                            </p>
                            
                            <div className="flex items-center gap-4 border-t border-white/5 pt-4">
                              <a 
                                href={`https://me.sap.com/notes/${note.id}`} 
                                target="_blank"
                                rel="noopener noreferrer"
                                className="flex items-center gap-2 text-xs font-mono text-cyan-400 hover:text-cyan-300 transition-colors uppercase tracking-widest bg-cyan-500/10 px-4 py-2 rounded-lg border border-cyan-500/30 w-fit"
                              >
                                View Official Note in SAP For Me <ExternalLink size={14} />
                              </a>
                            </div>
                          </div>
                        </motion.div>
                      )}
                    </AnimatePresence>
                  </motion.div>
                ))}
              </div>
            ) : (
              <div className="text-center py-12 border border-white/5 border-dashed rounded-xl bg-[#0f172a]/20">
                <FileText size={48} className="mx-auto text-slate-600 mb-4" />
                <p className="text-slate-400 font-mono text-sm">No notes found matching "{searchQuery}"</p>
              </div>
            )}
          </div>

        </div>
      </div>
    </div>
  );
}
